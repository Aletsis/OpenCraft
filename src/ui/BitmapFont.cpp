Glyph buildGlyph(const GlyphArt& art) {
    Glyph g;
    int maxCol = -1;
    for (int r = 0; r < 8; ++r) {
        uint8_t bits = 0;
        for (int c = 0; c < 5; ++c) {
            if (art.rows[r][c] == '#') {
                bits |= static_cast<uint8_t>(1u << (4 - c));
                if (c > maxCol) maxCol = c;
            }
        }
        g.rows[r] = bits;
    }
    g.advance = static_cast<uint8_t>(maxCol + 2);
    return g;
}

const std::unordered_map<char32_t, Glyph>& glyphTable() {
    static const std::unordered_map<char32_t, Glyph> table = [] {
        std::unordered_map<char32_t, Glyph> t;
        for (const auto& art : GLYPH_ART) {
            t.emplace(art.cp, buildGlyph(art));
        }
        Glyph space;
        space.advance = 4;
        t.emplace(U' ', space);
        return t;
    }();
    return table;
}

// Las mayúsculas acentuadas no caben en 7 filas: se muestran sin tilde
char32_t foldCodepoint(char32_t cp) {
    switch (cp) {
        case U'Á': return U'A';
        case U'É': return U'E';
        case U'Í': return U'I';
        case U'Ó': return U'O';
        case U'Ú':
        case U'Ü': return U'U';
        case U'à':
        case U'â':
        case U'ä': return U'á';
        case U'è':
        case U'ê':
        case U'ë': return U'é';
        case U'ì':
        case U'î':
        case U'ï': return U'í';
        case U'ò':
        case U'ô':
        case U'ö': return U'ó';
        case U'ù':
        case U'û': return U'ú';
        case U'ç': return U'c';
        case U'Ç': return U'C';
        case U'—':
        case U'–': return U'-';
        case U'\t': return U' ';
        default: return cp;
    }
}

