std::vector<char32_t> decodeUtf8(std::string_view text) {
    std::vector<char32_t> out;
    out.reserve(text.size());
    size_t i = 0;
    while (i < text.size()) {
        auto b0 = static_cast<unsigned char>(text[i]);
        char32_t cp = U'?';
        size_t len = 1;
        if (b0 < 0x80) {
            cp = b0;
        } else if ((b0 & 0xE0) == 0xC0) {
            len = 2;
        } else if ((b0 & 0xF0) == 0xE0) {
            len = 3;
        } else if ((b0 & 0xF8) == 0xF0) {
            len = 4;
        }
        if (len > 1) {
            if (i + len > text.size()) {
                out.push_back(U'?');
                break;
            }
            cp = (len == 2) ? (b0 & 0x1F) : (len == 3) ? (b0 & 0x0F) : (b0 & 0x07);
            bool valid = true;
            for (size_t k = 1; k < len; ++k) {
                auto bk = static_cast<unsigned char>(text[i + k]);
                if ((bk & 0xC0) != 0x80) {
                    valid = false;
                    break;
                }
                cp = (cp << 6) | (bk & 0x3F);
            }
            if (!valid) {
                cp = U'?';
                len = 1;
            }
        }
        out.push_back(cp);
        i += len;
    }
    return out;
}

const Glyph& glyphFor(char32_t codepoint) {
    const auto& table = glyphTable();
    auto it = table.find(foldCodepoint(codepoint));
    if (it != table.end()) return it->second;
    return table.at(U'?');
}

int measure(std::string_view text) {
    int width = 0;
    for (char32_t cp : decodeUtf8(text)) {
        width += glyphFor(cp).advance;
    }
    return width > 0 ? width - 1 : 0;
}

