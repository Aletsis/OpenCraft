std::string localizedItemName(uint16_t itemId) {
    const auto& def = ItemRegistry::global().get(itemId);
    std::string_view id = def.namespacedId;
    if (id.starts_with("opencraft:")) id.remove_prefix(10);
    auto it = names().find(id);
    if (it != names().end()) return std::string(it->second);
    return def.displayName;
}

